# Per-game generator for the cheats mod, called by ..\..\build.ps1.
# Turns PerGame.<game>.Presets from mod.psd1 into:
#   $OutDir\cheat_presets.h   the preset table cheats.c applies
#   PRESET_OPTIONS            one Bool option per preset in the manifest (default off)
param([string]$Game, [hashtable]$Overrides, [string]$OutDir)

$presets = @($Overrides.Presets | Where-Object { $_ })
if ($presets.Count -gt 32) { throw "${Game}: at most 32 presets (cheats.c tracks them in a u32 mask)" }

function TomlString([string]$s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }

$entries = @()
$options = @()
foreach ($p in $presets) {
    if ($p.Id -notmatch '^[a-z0-9_]+$') { throw "${Game}: preset id '$($p.Id)' must be [a-z0-9_]" }
    if ($p.Id -in @('codes', 'code_version')) { throw "${Game}: preset id '$($p.Id)' is reserved" }
    if ($p.Codes -notmatch '^[0-9A-Fa-f ]+$') { throw "${Game}: preset '$($p.Id)' codes must be hex and spaces" }
    $entries += "    { `"$($p.Id)`", `"$($p.Codes)`" },"
    $options += @"

[[manifest.config_options]]
id = "$($p.Id)"
name = $(TomlString $p.Name)
description = $(TomlString "$($p.Description) Code: $($p.Codes)")
type = "Bool"
default = false
"@
}

$header = @"
// Generated by mods/cheats/generate.ps1 for '$Game' -- do not edit.
// Presets are written for the ROM revision this recomp uses (no translation).
#define NUM_PRESETS $($presets.Count)
static const Preset cheat_presets[NUM_PRESETS > 0 ? NUM_PRESETS : 1] = {
$(if ($entries) { $entries -join "`n" } else { '    { "", "" },' })
};
"@
[IO.File]::WriteAllText("$OutDir\cheat_presets.h", $header)

@{ PRESET_OPTIONS = ($options -join '') }
