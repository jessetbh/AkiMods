# Per-game generator for the quickmatch mod, called by ..\..\build.ps1.
# Turns PerGame.<game>.Venues / .Matches / .Lengths from mod.psd1 into:
#   $OutDir\quickmatch_game.h   QM_VENUE_IDS / QM_LENGTH_IDS (game ids in option order), QM_CATEGORIES
#   VENUE_OPTIONS, MATCH_OPTIONS, LENGTH_OPTIONS / LENGTH_DEFAULT   manifest enum lists
#   (the first Lengths entry is the default)
param([string]$Game, [hashtable]$Overrides, [string]$OutDir)

$venues = @($Overrides.Venues | Where-Object { $_ })
$matchList = @($Overrides.Matches | Where-Object { $_ })
$lengths = @($Overrides.Lengths | Where-Object { $_ })
if ($venues.Count -eq 0) { throw "${Game}: quickmatch needs PerGame.$Game.Venues" }

function TomlString([string]$s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }
function TomlList([string[]]$items) { '[ ' + (($items | ForEach-Object { TomlString $_ }) -join ', ') + ' ]' }

$venueNames = @("Game's pick") + @($venues | ForEach-Object { $_.Name })
$matchNames = @("Game's rotation") + @($matchList | ForEach-Object { $_ })
$lengthNames = @($lengths | ForEach-Object { $_.Name } | Where-Object { $_ })
foreach ($list in $venueNames, $matchNames, $lengthNames) {
    $dupes = $list | Group-Object | Where-Object { $_.Count -gt 1 }
    if ($dupes) { throw "${Game}: duplicate option names: $($dupes.Name -join ', ')" }
}

$ids = ($venues | ForEach-Object { [int]$_.Id }) -join ', '
$header = @"
// Generated by mods/quickmatch/generate.ps1 for '$Game' -- do not edit.
#define QM_VENUE_IDS $ids
#define QM_CATEGORIES $($matchList.Count)
"@
if ($lengths.Count -gt 0) { $header += "`n#define QM_LENGTH_IDS $(($lengths | ForEach-Object { [int]$_.Id }) -join ', ')" }
[IO.File]::WriteAllText("$OutDir\quickmatch_game.h", $header)

$lengthOption = ''
if ($lengths.Count -gt 0) {
    $lengthOption = @'
[[manifest.config_options]]
id = "length"
name = "Demo length"
description = "How long the demo match runs before the game goes back to the title (and the next demo starts). A pinfall or submission still ends it early."
type = "Enum"
options = {{LENGTH_OPTIONS}}
default = {{LENGTH_DEFAULT}}


'@.Replace('{{LENGTH_OPTIONS}}', (TomlList $lengthNames)).Replace('{{LENGTH_DEFAULT}}', (TomlString $lengthNames[0]))
}

# Manifest texts. The defaults describe the attract-demo games (No Mercy); menu-driven games override them.
$text = @{
    SHORT_DESCRIPTION   = 'Developer tool: boot straight into the demo match in a chosen venue.'
    DESCRIPTION         = "A testing tool for {{GAME_TITLE}}: with Enabled on, the game skips its intro and starts the attract-mode demo match right away, in the venue you pick, instead of after a minute or more of intro and title screen. The demo is the game's own CPU-vs-CPU match, so there is no HUD and no controller input.`n`nOff by default. Turn it off again for normal play: while it's on, the title screen never waits for you."
    ENABLED_DESCRIPTION = 'Skip the intro and title wait, and start the demo match with the settings below.'
    VENUE_DESCRIPTION   = 'Where the demo match takes place.'
    MATCH_DESCRIPTION   = "Which of the game's demo matches to play (wrestlers and match type)."
}
if ($Overrides.Text) { foreach ($k in $Overrides.Text.Keys) { $text[$k] = $Overrides.Text[$k] } }

$result = @{
    VENUE_OPTIONS = TomlList $venueNames
    MATCH_OPTIONS = TomlList $matchNames
    LENGTH_OPTION = $lengthOption
}
foreach ($k in $text.Keys) { $result[$k] = $text[$k] }
$result
